"""E13-T05b AC3: VB posterior means agree with MAP within 2 % for flat-ish priors (T >= 20 000)."""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest

from hsmmkit.config.schema import EstimationSection
from hsmmkit.estimation.map import fit as map_fit
from hsmmkit.estimation.vb import VBEstimator
from hsmmkit.model.params.manager import ParamManager
from tests.helpers import em_models

_ROWS = [
    ("gaussian", "geometric"),
    ("gaussian_full", "geometric"),
    ("poisson", "negbin"),
    ("categorical", "geometric"),
]
_RESULTS: list[tuple[str, str, float, str]] = []
_REPORT = Path(__file__).resolve().parents[2] / "docs" / "generated" / "vb_parity.md"


@pytest.mark.parametrize(("family", "duration"), _ROWS, ids=[f"{f}-{d}" for f, d in _ROWS])
def test_e13_t05b_vb_posterior_means_match_map(tmp_path: Path, family: str, duration: str) -> None:
    """Every free parameter within 2 % (relative, `atol = 1e-3` for entries near zero)."""
    spec, theta0 = em_models.build(tmp_path, family, duration)
    data = em_models.dataset(family, 20_000, 5)
    start = ParamManager(spec.param_specs).flatten(theta0)
    vb = VBEstimator().fit(
        spec, data, EstimationSection(method="vb", restarts=0, max_iter=300, tol_f=1e-11), 0, warm_start=start
    )
    mp = map_fit(
        spec,
        data,
        EstimationSection(restarts=0, max_iter=3000, tol_f=1e-14, tol_g=1e-9, use_priors=False),
        0,
        warm_start=start,
    )
    worst = 0.0
    for name, value in mp.params.items():
        if name == "transition.pi_rows":  # two regimes: the jump row is 1
            continue
        a, b = np.asarray(vb.params[name]), np.asarray(value)
        worst = max(worst, float(np.max(np.abs(a - b) / np.maximum(np.abs(b), 0.05))))
    _RESULTS.append((family, duration, worst, "ok" if worst <= 0.02 else "FAILED"))
    _write()
    assert worst <= 0.02, worst


def _write() -> None:
    lines = [
        "# VB posterior means vs MAP (generated by `tests/parity/test_e13_t05b_vb_map.py`)",
        "",
        "| emission | duration | max relative difference (T = 20 000) | status |",
        "|---|---|---|---|",
        *[f"| {f} | {d} | {w:.2e} | {s} |" for f, d, w, s in sorted(_RESULTS)],
        "",
    ]
    _REPORT.parent.mkdir(parents=True, exist_ok=True)
    _REPORT.write_text("\n".join(lines))
