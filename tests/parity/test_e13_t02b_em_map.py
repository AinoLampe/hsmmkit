"""E13-T02b AC2: EM (closed form / ECM) reaches the MAP optimum from the same start; writes `em_parity.md`."""

from __future__ import annotations

import os
from pathlib import Path
from typing import Any

import numpy as np
import pytest

from hsmmkit.config.schema import EstimationSection
from hsmmkit.estimation.em import EMEstimator
from hsmmkit.estimation.map import fit as map_fit
from hsmmkit.model.params.manager import ParamManager
from tests.helpers import em_models

_ROWS: list[tuple[str, str, dict[str, Any]]] = [
    ("gaussian", "geometric", {}),
    ("gaussian", "negbin", {}),
    ("gaussian_full", "geometric", {}),
    ("student_t", "geometric", {}),
    ("poisson", "geometric", {}),
    ("poisson", "negbin", {}),
    ("categorical", "negbin", {}),
    ("gaussian", "geometric", {"topology": {"matrix": [[0, 1], [0, 0]]}}),
]
_RESULTS: list[tuple[str, str, str, str, float, float, str]] = []
_REPORT = Path(__file__).resolve().parents[2] / "docs" / "generated" / "em_parity.md"


def _row_id(row: tuple[str, str, dict[str, Any]]) -> str:
    return f"{row[0]}-{row[1]}-{'ltr' if row[2] else 'full'}"


@pytest.mark.parametrize("row", _ROWS, ids=_row_id)
def test_e13_t02b_em_parity_with_map(tmp_path: Path, row: tuple[str, str, dict[str, Any]]) -> None:
    """No priors, same start: parameters rel <= 1e-4, loglik rel <= 1e-6 (Appendix G)."""
    family, duration, extra = row
    spec, theta0 = em_models.build(tmp_path, family, duration, **extra)
    data = em_models.dataset(family, 1200, 4)
    start = ParamManager(spec.param_specs).flatten(theta0)
    em_cfg = EstimationSection(restarts=0, max_iter=30000, tol_f=1e-15, use_priors=False)
    map_cfg = EstimationSection(restarts=0, max_iter=4000, tol_f=1e-15, tol_g=1e-9, use_priors=False)
    em = EMEstimator().fit(spec, data, em_cfg, 0, warm_start=start)
    mp = map_fit(spec, data, map_cfg, 0, warm_start=start)
    plan = em.diagnostics["em"]
    rel_ll = abs(em.loglik - mp.loglik) / abs(mp.loglik)
    worst = max(
        float(np.max(np.abs(np.asarray(em.params[k]) - np.asarray(v)) / (np.abs(np.asarray(v)) + 1e-6)))
        for k, v in mp.params.items()
        if k in em.params and np.asarray(v).size
    )
    status = "ok" if rel_ll <= 1e-6 and worst <= 1e-4 else "FAILED"
    _RESULTS.append((family, duration, "LTR" if extra else "full", plan["emission"], rel_ll, worst, status))
    if os.environ.get("HSMMKIT_WRITE_PARITY") == "1":
        _write()
    assert rel_ll <= 1e-6
    for name, value in mp.params.items():
        np.testing.assert_allclose(
            np.asarray(em.params[name]), np.asarray(value), rtol=1e-4, atol=1e-6, err_msg=name
        )


def _write() -> None:
    lines = [
        "# EM vs MAP parity (generated by `tests/parity/test_e13_t02b_em_map.py`)",
        "",
        "| emission | duration | topology | emission block | loglik rel | max param rel | status |",
        "|---|---|---|---|---|---|---|",
    ]
    lines += [
        f"| {f} | {d} | {t} | {m} | {ll:.1e} | {pr:.1e} | {st} |"
        for f, d, t, m, ll, pr, st in sorted(_RESULTS)
    ]
    lines += [
        "",
        "Not in the table: `msar` and `mixture` rows (they need their own preparer / component-labelling",
        "fixtures; recorded as a Follow-up) and covariate-link rows (ECM, see `test_e13_t02b_ecm.py`).",
        "",
    ]
    _REPORT.parent.mkdir(parents=True, exist_ok=True)
    _REPORT.write_text("\n".join(lines))
