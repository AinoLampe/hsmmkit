"""Parity checks shared by the parity suite and its regression test (E13-T07; not collected).

Each `evaluate_*` function runs one comparison between two estimators and returns a `ParityRow` whose
`status` is `"ok"` or `"FAILED"` (it never asserts), so that the suite can record the row and a regression
test can show that a deliberately broken component turns a row red.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np

from hsmmkit.config.schema import EstimationSection
from hsmmkit.estimation.em import EMEstimator
from hsmmkit.estimation.gem import GEMEstimator
from hsmmkit.estimation.map import fit as map_fit
from hsmmkit.estimation.vb import VBEstimator
from hsmmkit.model.params.manager import ParamManager
from tests.helpers import em_models, gem_models

HEADER = ("model", "estimators", "check", "tolerance (Appendix G)", "result", "seeds passed", "status")


@dataclass(frozen=True)
class ParityRow:
    """One row of `docs/generated/estimator_parity.md`."""

    model: str
    estimators: str
    check: str
    tolerance: str
    result: str
    seeds: str
    status: str

    def cells(self) -> tuple[str, ...]:
        """The table cells in `HEADER` order."""
        return (self.model, self.estimators, self.check, self.tolerance, self.result, self.seeds, self.status)


def render(rows: list[ParityRow]) -> str:
    """The markdown table of `rows` (sorted)."""
    lines = [
        "# Estimator parity (generated by `scripts/gen_parity_table.py`)",
        "",
        "Regenerate with `uv run python scripts/gen_parity_table.py` (add `--slow` for the sampler rows). "
        "Every row must be `ok`; the nightly `parity` job fails otherwise.",
        "",
        "| " + " | ".join(HEADER) + " |",
        "|" + "---|" * len(HEADER),
        *[
            "| " + " | ".join(r.cells()) + " |"
            for r in sorted(rows, key=lambda r: (r.estimators, r.model, r.check))
        ],
        "",
    ]
    return "\n".join(lines)


def _worst_rel(a: dict[str, Any], b: dict[str, Any], floor: float) -> float:
    worst = 0.0
    for name, value in b.items():
        if name == "transition.pi_rows" or name not in a:  # two regimes: the jump row is 1
            continue
        x, y = np.asarray(a[name]), np.asarray(value)
        if y.size:
            worst = max(worst, float(np.max(np.abs(x - y) / np.maximum(np.abs(y), floor))))
    return worst


def evaluate_em_vs_map(tmp_path: Path, family: str, duration: str, extra: dict[str, Any]) -> ParityRow:
    """EM (closed form / ECM) vs MAP from the same start, no priors: loglik rel 1e-6, parameters rel 1e-4."""
    spec, theta0 = em_models.build(tmp_path, family, duration, **extra)
    data = em_models.dataset(family, 1200, 4)
    start = ParamManager(spec.param_specs).flatten(theta0)
    em_cfg = EstimationSection(restarts=0, max_iter=30000, tol_f=1e-15, use_priors=False)
    map_cfg = EstimationSection(restarts=0, max_iter=4000, tol_f=1e-15, tol_g=1e-9, use_priors=False)
    em = EMEstimator().fit(spec, data, em_cfg, 0, warm_start=start)
    mp = map_fit(spec, data, map_cfg, 0, warm_start=start)
    rel_ll = abs(em.loglik - mp.loglik) / abs(mp.loglik)
    rel_p = _worst_rel(em.params, mp.params, 1e-6)
    ok = rel_ll <= 1e-6 and rel_p <= 1e-4
    topology = "LTR" if extra else "full"
    block = em.diagnostics["em"]["emission"]
    return ParityRow(
        f"{family} / {duration} / {topology}",
        "em vs map",
        f"same start, no priors ({block})",
        "loglik rel 1e-6; params rel 1e-4",
        f"loglik {rel_ll:.1e}; params {rel_p:.1e}",
        "1/1" if ok else "0/1",
        "ok" if ok else "FAILED",
    )


def evaluate_vb_vs_map(tmp_path: Path, family: str, duration: str) -> ParityRow:
    """VB posterior means vs MAP at T = 20 000 (flat-ish priors): every parameter within 2 %."""
    spec, theta0 = em_models.build(tmp_path, family, duration)
    data = em_models.dataset(family, 20_000, 5)
    start = ParamManager(spec.param_specs).flatten(theta0)
    vb = VBEstimator().fit(
        spec, data, EstimationSection(method="vb", restarts=0, max_iter=300, tol_f=1e-11), 0, warm_start=start
    )
    mp = map_fit(
        spec,
        data,
        EstimationSection(restarts=0, max_iter=3000, tol_f=1e-14, tol_g=1e-9, use_priors=False),
        0,
        warm_start=start,
    )
    worst = _worst_rel(vb.params, mp.params, 0.05)
    ok = worst <= 0.02
    return ParityRow(
        f"{family} / {duration}",
        "vb vs map",
        "posterior means, T = 20 000",
        "params rel 2 %",
        f"params {worst:.1e}",
        "1/1" if ok else "0/1",
        "ok" if ok else "FAILED",
    )


def evaluate_gem_vs_em(tmp_path: Path) -> ParityRow:
    """GEM (explicit engine, geometric) vs EM (expanded engine), no priors: the same optimum."""
    rng = np.random.default_rng(5)
    z = np.zeros(900, dtype=int)
    s = 0
    for t in range(900):
        z[t] = s
        if rng.random() < 0.25:
            s = 1 - s
    y = rng.normal(np.where(z == 0, -1.0, 1.0), np.where(z == 0, 0.6, 0.9))[:, None]
    data = gem_models.dataset(y)
    kw = {"means": [-0.4, 0.4], "scales": [0.8, 0.8], "duration": "geometric", "mean_sojourn": 4.0}
    spec_x = gem_models.build(tmp_path, 2, 100, **kw)
    spec_e = gem_models.build(tmp_path, 2, 100, engine="expanded", **kw)
    cfg = EstimationSection(restarts=0, max_iter=4000, tol_f=1e-15, use_priors=False)
    gem = GEMEstimator().fit(spec_x, data, cfg, 0, warm_start=ParamManager(spec_x.param_specs).init_u())
    em = EMEstimator().fit(spec_e, data, cfg, 0, warm_start=ParamManager(spec_e.param_specs).init_u())
    rel_ll = abs(gem.loglik - em.loglik) / abs(em.loglik)
    rel_p = _worst_rel(gem.params, em.params, 1e-6)
    ok = rel_ll <= 1e-6 and rel_p <= 1e-4
    return ParityRow(
        "gaussian / geometric (D_max 100)",
        "gem (explicit) vs em (expanded)",
        "same start, no priors",
        "loglik rel 1e-6; params rel 1e-4",
        f"loglik {rel_ll:.1e}; params {rel_p:.1e}",
        "1/1" if ok else "0/1",
        "ok" if ok else "FAILED",
    )


def evaluate_gem_vs_map_gamma(tmp_path: Path) -> ParityRow:
    """GEM vs MAP with gamma durations (weighted MLE by Newton), no priors, same start."""
    cfg_dur = {
        "family": "gamma",
        "params": {
            "shape": {"mode": "free", "init": [2.0, 2.0]},
            "scale": {"mode": "free", "init": [2.5, 3.0]},
        },
    }
    spec = gem_models.build(tmp_path, 2, 25, duration_cfg=cfg_dur, means=[-0.5, 0.5], scales=[0.8, 0.8])
    pmf = np.zeros((2, 25))
    d = np.arange(1, 26)
    pmf[0] = np.exp(-0.5 * ((d - 5) / 2.0) ** 2)
    pmf[1] = np.exp(-0.5 * ((d - 9) / 3.0) ** 2)
    pmf /= pmf.sum(axis=1, keepdims=True)
    y, _ = gem_models.simulate(
        900, pmf, np.array([[0.0, 1.0], [1.0, 0.0]]), np.array([-1.0, 1.0]), np.array([0.6, 0.9]), 3
    )
    data = gem_models.dataset(y)
    start = ParamManager(spec.param_specs).init_u()
    gem = GEMEstimator().fit(
        spec,
        data,
        EstimationSection(restarts=0, max_iter=6000, tol_f=1e-15, use_priors=False),
        0,
        warm_start=start,
    )
    mp = map_fit(
        spec,
        data,
        EstimationSection(restarts=0, max_iter=3000, tol_f=1e-15, tol_g=1e-9, use_priors=False),
        0,
        warm_start=start,
    )
    rel_ll = abs(gem.loglik - mp.loglik) / abs(mp.loglik)
    rel_p = _worst_rel(gem.params, mp.params, 1e-6)
    ok = rel_ll <= 1e-6 and rel_p <= 1e-4
    return ParityRow(
        "gaussian / gamma (explicit)",
        "gem vs map",
        "same start, no priors",
        "loglik rel 1e-6; params rel 1e-4",
        f"loglik {rel_ll:.1e}; params {rel_p:.1e}",
        "1/1" if ok else "0/1",
        "ok" if ok else "FAILED",
    )
