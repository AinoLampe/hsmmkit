MAX_MEAN_ADJUSTED_ORDER = 2


@dataclass(frozen=True)
class MatrixNormalWishart:
    """Matrix-Normal-Wishart prior on the regression `(B_i, Sigma_i)` of each regime.

    `B | Sigma ~ MN(B0, Lambda0^-1, Sigma)` (`B` is `(1 + pM, M)`: intercept row, then the lag blocks),
    `Sigma^-1 ~ Wishart(W0, nu0)`. `B0 = 0`, `Lambda0 = kappa0 I` and `W0 = I` by default.
    """

    kappa0: float = 0.01
    nu0: float | None = None
    b0: Array | None = None
    w0: Array | None = None

    def update(self, stats: dict[str, Array]) -> dict[str, Array]:
        """Posterior `(B, Lambda, W, nu)` per regime from `sufficient_stats`."""
        n, sxx, sxy, syy = stats["n"], stats["sxx"], stats["sxy"], stats["syy"]
        d, m = sxy.shape[1], sxy.shape[2]
        b0 = jnp.zeros((d, m)) if self.b0 is None else self.b0
        w0 = jnp.eye(m) if self.w0 is None else self.w0
        nu0 = float(m + 2) if self.nu0 is None else self.nu0
        lam0 = self.kappa0 * jnp.eye(d)
        lam = lam0[None] + sxx
        rhs = (lam0 @ b0)[None] + sxy
        b_post = jnp.linalg.solve(lam, rhs)
        b0_term = b0.T @ lam0 @ b0
        w_inv = (
            jnp.linalg.inv(w0)[None]
            + syy
            + b0_term[None]
            - jnp.einsum("ndm,ndk,nkj->nmj", b_post, lam, b_post)
        )
        w_inv = 0.5 * (w_inv + jnp.swapaxes(w_inv, -1, -2))
        return {"B": b_post, "Lambda": lam, "W": jnp.linalg.inv(w_inv), "nu": nu0 + n}


def _ar_spec(cfg: ParamCfg | None, shape: tuple[int, ...], n_states: int, *, shared: bool) -> ParamSpec:
    """`emission.ar`: free by default (zero start, `N(0, 1)` prior); `init`/`values` are flat lists.

    A flat list has either one value per entry of a single regime's block (broadcast to every regime) or
    one per entry of the full parameter.
    """
    size = int(np.prod(shape))
    block = size if shared else size // n_states

    def expand(raw: list[float] | float | str | None, what: str) -> np.ndarray | None:
        if raw is None:
            return None
        if isinstance(raw, str):
            raise ConfigError(
                f"{what}: {raw!r} is not available for emission.ar", path=f"model.emission.params.ar.{what}"
            )
        flat = np.atleast_1d(np.asarray(raw, dtype=np.float64))
        if flat.size == 1:
            flat = np.full(block, float(flat[0]))
        if flat.size == block:
            return (
                np.broadcast_to(flat, (size,)).reshape(shape)
                if shared
                else np.tile(flat, n_states).reshape(shape)
            )
        if flat.size == size:
            return flat.reshape(shape)
        raise ConfigError(
            f"expected {block} (or {size}) entries for emission.ar of shape {shape}, got {flat.size}",
            path=f"model.emission.params.ar.{what}",
        )

    if cfg is None:
        return ParamSpec(
            name="emission.ar",
            shape=shape,
            domain="real",
            mode="free",
            init=np.zeros(shape),
            prior=DEFAULT_COEF_PRIOR,
        )
    if cfg.constraint != "none" or cfg.bounds is not None or cfg.tie is not None:
        raise ConfigError(
            "emission.ar supports neither constraint, bounds nor tie", path="model.emission.params.ar"
        )
    values = expand(cfg.values, "values")
    init = expand(cfg.init, "init")
    if init is None and cfg.mode != "fixed":
        init = np.zeros(shape)
    prior = None
    if cfg.prior is not None:
        if cfg.prior.type != "normal":
            raise ConfigError(
                f"prior type {cfg.prior.type!r} is not valid for emission.ar (normal)",
                path="model.emission.params.ar.prior.type",
            )
        prior = NormalPrior(sd=cfg.prior.sd if cfg.prior.sd is not None else 1.0)
    return ParamSpec(
        name="emission.ar", shape=shape, domain="real", mode=cfg.mode, value=values, init=init, prior=prior
    )


@register("emission", "msar")
@dataclass(frozen=True)
class MSARFamily(BaseEmission):
    """Gaussian MS-AR(p) emission on preparer-generated own-lag covariates.

    Attributes:
        p: autoregressive order.
        n_series: number of series `M` (the lag block of `z` has `p * M` columns).
        form: `coefficients` or `mean_adjusted`.
        covariance: `diag` (`emission.scale`) or `full` (`emission.chol`).
    """

    p: int = 1
    n_series: int = 1
    form: Literal["coefficients", "mean_adjusted"] = "coefficients"
    covariance: Literal["diag", "full"] = "diag"
    name: str = "msar"
    native_time: Literal["continuous", "discrete"] = "discrete"
    support: Support = "real"
    scale_by_dt: bool = False

    joint: ClassVar[bool] = True
    """No per-series factorization (the lags couple the series): `model/build.py` skips `ProductEmission`."""

    def __post_init__(self) -> None:
        """Validate the order."""
        if self.p < 1:
            raise ConfigError(f"AR order must be >= 1, got {self.p}", path="model.emission.ar.p")
        if self.form == "mean_adjusted" and self.p > MAX_MEAN_ADJUSTED_ORDER:
            raise ConfigError("mean-adjusted MS-AR supports p <= 2", path="model.emission.params.p")

    @staticmethod
    def lags_required(cfg: EmissionCfg) -> int:
        """Own lags the preparer generates for this configuration (`model.emission.ar.p`)."""
        return 0 if cfg.ar is None else cfg.ar.p

    # --- declarations used by the preparer / state-space builder ----------------------------------

    @property
    def requires_own_lags(self) -> int:
        """Number of own lags the preparer must append as emission covariates."""
        return self.p

    @property
    def memory_steps(self) -> int:
        """Time-step memory the state space needs: `p` for the mean-adjusted form, else `0`."""
        return self.p if self.form == "mean_adjusted" else 0

    @property
    def mean_name(self) -> str:
        """Name of the location parameter (`emission.intercept` or `emission.mean`)."""
        return "emission.intercept" if self.form == "coefficients" else "emission.mean"

    @property
    def series_param_names(self) -> tuple[str, ...]:
        """Parameters with a series axis (`ProductEmission` is never used; kept for symmetry)."""
        return (self.mean_name,)

    @property
    def shared_param_names(self) -> tuple[str, ...]:
        """Parameters without a state axis (the AR coefficients of the mean-adjusted form)."""
        return ("emission.ar",) if self.form == "mean_adjusted" else ()

    # --- parameter layout --------------------------------------------------------------------------

    def _ar_shape(self, n_states: int, n_series: int) -> tuple[int, ...]:
        shared = (self.p, n_series, n_series)
        return shared if self.form == "mean_adjusted" else (n_states, *shared)

    def param_specs(self, n_states: int, n_series: int, cov_names: tuple[str, ...]) -> tuple[ParamSpec, ...]:
        """Default (config-free) specs: location, free AR coefficients and the scale."""
        del cov_names
        loc = ParamSpec(
            name=self.mean_name,
            shape=(n_states, n_series),
            domain="real",
            mode="free",
            init=np.zeros((n_states, n_series)),
        )
        ar = _ar_spec(None, self._ar_shape(n_states, n_series), n_states, shared=self.form == "mean_adjusted")
        if self.covariance == "full":
            return (loc, ar, _chol_spec(n_states, n_series, None, mode="free", prior=None))
        scale = ParamSpec(
            name="emission.scale",
            shape=(n_states, n_series),
            domain="positive",
            mode="free",
            init=np.ones((n_states, n_series)),
        )
        return (loc, ar, scale)

    @classmethod
    def from_config(
        cls, cfg: EmissionCfg, n_states: int, n_series: int, cov_names: tuple[str, ...]
    ) -> tuple[MSARFamily, tuple[ParamSpec, ...]]:
        """Map `model.emission` (with `ar: {p, form}`) to a configured family and its `ParamSpec`s."""
        if cfg.ar is None:
            raise ConfigError("the msar emission requires model.emission.ar", path="model.emission.ar")
        if cfg.scale_by_dt or cfg.ito_correction or cfg.mixture is not None:
            raise ConfigError(
                "msar takes neither scale_by_dt, ito_correction nor a mixture", path="model.emission"
            )
        if any(getattr(cfg.covariates, k) for k in ("mean", "log_scale", "drift", "log_vol")):
            raise ConfigError(
                "msar takes no emission covariates besides its own lags", path="model.emission.covariates"
            )
        if not cfg.per_series:
            raise ConfigError("msar has no shared-across-series parameters", path="model.emission.per_series")
        p, form = cfg.ar.p, cfg.ar.form
        if form == "mean_adjusted" and p > MAX_MEAN_ADJUSTED_ORDER:
            raise ConfigError("mean-adjusted MS-AR supports p <= 2", path="model.emission.params.p")
        expected = p * n_series
        if cov_names and (len(cov_names) != expected or not all(c.startswith(LAG_PREFIX) for c in cov_names)):
            raise ConfigError(
                f"msar expects the {expected} own-lag columns of the preparer (Preparer(..., own_lags={p})) "
                f"as its only emission covariates, got {list(cov_names)}",
                path="model.emission.covariates",
            )
        full = cfg.covariance == "full"
        family = cls(p=p, n_series=n_series, form=form, covariance=cfg.covariance)
        loc_key = "intercept" if form == "coefficients" else "mean"
        for required in (loc_key, "chol" if full else "scale"):
            if required not in cfg.params:
                raise ConfigError(
                    f"msar emission requires params.{required}", path=f"model.emission.params.{required}"
                )
        specs = [
            _spec_from_paramcfg(
                family.mean_name,
                cfg.params[loc_key],
                n_states=n_states,
                n_series=n_series,
                domain="real",
                default_init=0.0,
            ),
            _ar_spec(
                cfg.params.get("ar"),
                family._ar_shape(n_states, n_series),
                n_states,
                shared=form == "mean_adjusted",
            ),
            (
                _chol_spec_from_paramcfg(cfg.params["chol"], n_states, n_series)
                if full
                else _spec_from_paramcfg(
                    "emission.scale",
                    cfg.params["scale"],
                    n_states=n_states,
                    n_series=n_series,
                    domain="positive",
                    default_init=1.0,
                )
            ),
        ]
        unknown = set(cfg.params) - {loc_key, "ar", "chol" if full else "scale"}
        if unknown:
            raise ConfigError(
                f"unknown msar parameter(s) {sorted(unknown)}",
                path=f"model.emission.params.{sorted(unknown)[0]}",
            )
        return family, tuple(specs)

    # --- building blocks ----------------------------------------------------------------------------

    def _lags(self, z: Array | None, t: int) -> Array:
        """`(T, p, M)`: row `t` holds `y_{t-1}, ..., y_{t-p}` (zeros without covariates)."""
        if z is None:
            return jnp.zeros((t, self.p, self.n_series))
        return z[:, : self.p * self.n_series].reshape(t, self.p, self.n_series)

    def _loc(self, theta: dict[str, Array]) -> Array:
        """`(N, M)` location parameter (`(N,)` under `constraint: increasing` is lifted to `M = 1`)."""
        loc = theta[self.mean_name]
        return loc[:, None] if loc.ndim == 1 else loc

    def _scale(self, theta: dict[str, Array]) -> Array:
        """`(N, M)` diagonal scale (`(N,)` under `constraint: increasing` is lifted to `M = 1`)."""
        scale = theta["emission.scale"]
        return scale[:, None] if scale.ndim == 1 else scale

    def _factor(self, theta: dict[str, Array]) -> Array:
        """`(N, M, M)` lower-triangular covariance factor of every regime."""
        if self.covariance == "full":
            return unpack_lower(theta["emission.chol"], self.n_series)
        return jax.vmap(jnp.diag)(self._scale(theta))

    def _sd(self, theta: dict[str, Array]) -> Array:
        """`(N, M)` marginal standard deviations."""
        if self.covariance == "full":
            return jnp.sqrt(jnp.sum(self._factor(theta) ** 2, axis=-1))
        return self._scale(theta)

    def _cond_mean(self, theta: dict[str, Array], lags: Array) -> Array:
        """`(T, N, M)` conditional mean of the `coefficients` form."""
        return self._loc(theta)[None] + jnp.einsum("nplk,tpk->tnl", theta["emission.ar"], lags)

    def _density(self, y: Array, mean: Array, theta: dict[str, Array], regime_axis: Array | None) -> Array:
        """Gaussian log-density of `y (T, 1, M)` around `mean (T, K, M)` (`regime_axis`: covariance rows)."""
        if self.covariance == "full":
            chol = self._factor(theta)
            chol = chol if regime_axis is None else chol[regime_axis]
            return mvn_logpdf(y, mean, chol[None])
        sd = self._scale(theta)
        sd = sd if regime_axis is None else sd[regime_axis]
        return jnp.sum(normal_logpdf(y, mean, sd[None]), axis=-1)

    def _check_regime_form(self, what: str) -> None:
        if self.form == "mean_adjusted":
            raise ConfigError(
                f"the mean-adjusted msar has no per-regime {what}: its density depends on the regimes of the "
                "previous steps (use log_prob_tuples on the time-step state space)",
                path="model.emission.ar.form",
            )

    # --- protocol: numerics ---------------------------------------------------------------------------

    def log_prob(self, y: Array, dt: Array, theta: dict[str, Array], z: Array | None) -> Array:
        """`(T, N)` conditional log-density given the lags in `z` (`coefficients` form)."""
        self._check_regime_form("log_prob")
        mean = self._cond_mean(theta, self._lags(z, dt.shape[0]))
        return self._density(y[:, None, :], mean, theta, None)

    def log_prob_tuples(
        self, y: Array, dt: Array, theta: dict[str, Array], z: Array | None, tuples: Array
    ) -> Array:
        """`(T, S)` log-density of the mean-adjusted form for the regime tuples `(S, p + 1)`.

        `tuples[s] = (s_{t-p}, ..., s_t)`, oldest first; the density at step `t` is
        `N(mu_{s_t} + sum_l Phi_l (y_{t-l} - mu_{s_{t-l}}), Sigma_{s_t})`.
        """
        lags = self._lags(z, dt.shape[0])  # (T, p, M)
        current = tuples[:, self.p]
        history = tuples[:, : self.p][:, ::-1]  # (S, p): column l - 1 is s_{t-l}
        mu = self._loc(theta)
        dev = lags[:, None] - mu[history][None]  # (T, S, p, M)
        mean = mu[current][None] + jnp.einsum("plk,tspk->tsl", theta["emission.ar"], dev)
        return self._density(y[:, None, :], mean, theta, current)

    def cdf(self, y: Array, dt: Array, theta: dict[str, Array], z: Array | None) -> Array:
        """`(T, N, M)` marginal predictive CDF given the lags (`coefficients` form)."""
        self._check_regime_form("cdf")
        mean = self._cond_mean(theta, self._lags(z, dt.shape[0]))
        return jax.scipy.stats.norm.cdf((y[:, None, :] - mean) / self._sd(theta)[None])

    def _regime_mean(self, regime: Array, theta: dict[str, Array], lags: Array) -> Array:
        """`(T, M)` conditional mean along the regime path `(T,)`, given the lags `(T, p, M)`."""
        t = regime.shape[0]
        if self.form == "coefficients":
            return self._loc(theta)[regime] + jnp.einsum("tplk,tpk->tl", theta["emission.ar"][regime], lags)
        mu = self._loc(theta)
        # regimes at the previous steps; before the first step the first regime is repeated
        hist = jnp.stack(
            [regime[jnp.maximum(jnp.arange(t) - lag, 0)] for lag in range(1, self.p + 1)], axis=1
        )
        dev = lags - mu[hist]  # (T, p, M)
        return mu[regime] + jnp.einsum("plk,tpk->tl", theta["emission.ar"], dev)

    def sample(self, key: Array, regime: Array, dt: Array, theta: dict[str, Array], z: Array | None) -> Array:
        """`(T, M)` draws *given the lags in `z`* (teacher forcing); `sample_path` simulates the recursion."""
        mean = self._regime_mean(regime, theta, self._lags(z, dt.shape[0]))
        return self._noise(key, regime, mean, theta)

    def _noise(self, key: Array, regime: Array, mean: Array, theta: dict[str, Array]) -> Array:
        if self.covariance == "full":
            eps = jax.random.normal(key, mean.shape, dtype=mean.dtype)
            return mean + jnp.einsum("tij,tj->ti", self._factor(theta)[regime], eps)
        return sample_normal(key, mean, self._scale(theta)[regime], shape=mean.shape)

    def sample_path(
        self, key: Array, regime: Array, dt: Array, theta: dict[str, Array], y_init: Array | None = None
    ) -> Array:
        """`(T, M)` simulated autoregression along the regime path `(T,)`: each draw feeds the next lags.

        `y_init (p, M)` are the `p` values before the first step, most recent first (`y_{0}, y_{-1}, ...`);
        default zeros (the regime mean for the mean-adjusted form, so its first deviations vanish).
        """
        t = regime.shape[0]
        if y_init is None:
            y_init = (
                jnp.zeros((self.p, self.n_series))
                if self.form == "coefficients"
                else jnp.tile(self._loc(theta)[regime[0]][None], (self.p, 1))
            )
        keys = jax.random.split(key, t)

        def step(lags: Array, xs: tuple[Array, Array]) -> tuple[Array, Array]:
            k, idx = xs
            mean = (
                self._regime_mean(regime[idx][None], theta, lags[None])
                if self.form == "coefficients"
                else (self._mean_adjusted_step(regime, idx, theta, lags))
            )
            y_t = self._noise(k, regime[idx][None], mean, theta)[0]
            return jnp.concatenate([y_t[None], lags[:-1]], axis=0), y_t

        _, ys = jax.lax.scan(step, y_init, (keys, jnp.arange(t)))
        return ys

    def _mean_adjusted_step(self, regime: Array, idx: Array, theta: dict[str, Array], lags: Array) -> Array:
        """`(1, M)` mean of step `idx` of the mean-adjusted form from the carried lags."""
        mu = self._loc(theta)
        hist = regime[jnp.maximum(idx - jnp.arange(1, self.p + 1), 0)]  # (p,)
        dev = lags - mu[hist]
        return (mu[regime[idx]] + jnp.einsum("plk,pk->l", theta["emission.ar"], dev))[None]

    def moments(
        self, regime: Array, dt: Array, theta: dict[str, Array], z: Array | None
    ) -> tuple[Array, Array]:
        """Mean and variance `(T, M)` of the density *given the lags in `z`* (and the regimes of the path)."""
        mean = self._regime_mean(regime, theta, self._lags(z, dt.shape[0]))
        return mean, self._sd(theta)[regime] ** 2

    def init_carry(self) -> object:
        """No recursive carry: the lags are covariates."""
        return None

    def step_carry(self, carry: object, y_t: Array, theta: dict[str, Array]) -> object:
        """Identity."""
        del y_t, theta
        return carry

    # --- diagnostics ----------------------------------------------------------------------------------

    def spectral_radius(self, theta: dict[str, Array]) -> Array:
        """`(N,)` spectral radius of each regime's AR companion matrix (`< 1`: stationary)."""
        ar = theta["emission.ar"]
        if self.form == "mean_adjusted":
            ar = jnp.broadcast_to(ar[None], (self._loc(theta).shape[0], *ar.shape))
        n, p, m, _ = ar.shape
        top = jnp.concatenate([ar[:, i] for i in range(p)], axis=-1)  # (N, M, p M)
        if p == 1:
            comp = top
        else:
            eye = jnp.eye((p - 1) * m)
            bottom = jnp.concatenate([eye, jnp.zeros(((p - 1) * m, m))], axis=1)
            comp = jnp.concatenate([top, jnp.broadcast_to(bottom[None], (n, (p - 1) * m, p * m))], axis=1)
        return jnp.max(jnp.abs(jnp.linalg.eigvals(comp)), axis=-1)

    # --- estimation hooks -----------------------------------------------------------------------------

    def sufficient_stats(
        self, y: Array, dt: Array, gamma: Array, z: Array | None = None
    ) -> dict[str, Array] | None:
        """Weighted least-squares statistics per regime (`coefficients` form; `None` for mean-adjusted).

        With `X_t = [1, y_{t-1}, ..., y_{t-p}]` (`d = 1 + pM`): `n = sum gamma`, `sxx = sum gamma X X^T`,
        `sxy = sum gamma X y^T`, `syy = sum gamma y y^T`. `gamma` must be zero at masked steps.
        """
        if self.form != "coefficients":
            return None
        t = y.shape[0]
        x = jnp.concatenate([jnp.ones((t, 1)), self._lags(z, t).reshape(t, -1)], axis=1)  # (T, d)
        return {
            "n": jnp.sum(gamma, axis=0),
            "sxx": jnp.einsum("tn,tj,tk->njk", gamma, x, x),
            "sxy": jnp.einsum("tn,tj,tm->njm", gamma, x, y),
            "syy": jnp.einsum("tn,tj,tk->njk", gamma, y, y),
        }

    def m_step(self, stats: object) -> dict[str, Array] | None:
        """Closed-form weighted least squares: `B_i = sxx^-1 sxy`, `Sigma_i` from the weighted residuals."""
        if self.form != "coefficients" or not isinstance(stats, dict) or "sxx" not in stats:
            return None
        n, sxx, sxy, syy = stats["n"], stats["sxx"], stats["sxy"], stats["syy"]
        m = self.n_series
        b = jnp.linalg.solve(sxx, sxy)  # (N, d, M)
        sigma = (
            syy
            - jnp.einsum("ndm,ndk->nmk", b, sxy)
            - jnp.einsum("ndm,ndk->nkm", b, sxy)
            + jnp.einsum("ndm,ndk,nkj->nmj", b, sxx, b)
        ) / n[:, None, None]
        sigma = 0.5 * (sigma + jnp.swapaxes(sigma, -1, -2))
        intercept = b[:, 0, :]
        ar = jnp.swapaxes(b[:, 1:, :].reshape(b.shape[0], self.p, m, m), -1, -2)  # Phi_l[l, k] = B[k, l]^T
        out: dict[str, Array] = {"emission.intercept": intercept, "emission.ar": ar}
        if self.covariance == "full":
            jitter = 1e-10 * jnp.mean(jnp.diagonal(sigma, axis1=-2, axis2=-1), axis=-1)
            out["emission.chol"] = pack_lower(jnp.linalg.cholesky(sigma + jitter[:, None, None] * jnp.eye(m)))
        else:
            out["emission.scale"] = jnp.sqrt(jnp.diagonal(sigma, axis1=-2, axis2=-1))
        return out

    def conjugate_prior(self) -> MatrixNormalWishart | None:
        """Matrix-Normal-Wishart prior on `(B_i, Sigma_i)` (`coefficients` form with a full covariance)."""
        if self.form != "coefficients" or self.covariance != "full":
            return None
        return MatrixNormalWishart()


