"""Markov-switching autoregression MS-AR(p) emission (E11-T05, FR-EM04, FR-M09).

Two forms (`model.emission.ar.form`), both Gaussian with a diagonal or full covariance per regime:

`coefficients` (regime-dependent coefficients)::

    y_t = c_i + sum_{l=1}^{p} Phi_{i,l} y_{t-l} + eps_t,    eps_t ~ N(0, Sigma_i)

    emission.intercept (N, M)       c_i
    emission.ar        (N, p, M, M) Phi_{i,l}  (axis 1 is the lag l - 1)
    emission.scale (N, M) | emission.chol (N, M(M+1)/2)    Sigma_i, as in the `gaussian` family

`mean_adjusted` (Hamilton 1989, `p <= 2`)::

    y_t - mu_{s_t} = sum_{l=1}^{p} Phi_l (y_{t-l} - mu_{s_{t-l}}) + eps_t,    eps_t ~ N(0, Sigma_{s_t})

    emission.mean (N, M)   emission.ar (p, M, M), shared by all regimes   emission.scale | chol

The own lags `y_{t-1}, ..., y_{t-p}` are emission covariates generated by the preparer
(`Preparer(..., own_lags=p)`, named `__lag{l}_{series}`, ordered by lag then series), and the first `p`
steps are masked: the likelihood is conditional on the first `p` observations. Lags are `>= 1` by
construction, so no future value enters a density.

The mean-adjusted density depends on the regimes at the previous *time steps*, which the segment memory
of the expanded state space cannot express. That form therefore runs on the time-step state space
(`memory_mode: steps`, `N^(p+1)` tuples `(s_{t-p}, ..., s_t)`, geometric durations) and is evaluated per
tuple by `log_prob_tuples`; the per-regime `log_prob`/`cdf` do not exist for it.

Parameters are per step (`scale_by_dt` is false); no code here branches on the clock name.
"""

