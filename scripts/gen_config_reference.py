"""Generate `docs/guide/config.md` (the configuration reference) from the pydantic schema.

Usage:
    uv run python scripts/gen_config_reference.py            # (re)write docs/guide/config.md
    uv run python scripts/gen_config_reference.py --check    # exit 1 if the file is stale (CI diff check)

One table per config section with the field type and default, in schema order. The nox `docs` session
regenerates the page before `mkdocs build --strict`; `tests/unit/test_e8_t04_config_reference.py` fails when
the committed page differs from the schema.
"""

from __future__ import annotations

import sys
import types
import typing
from pathlib import Path, PurePath
from typing import Any

from pydantic import BaseModel
from pydantic_core import PydanticUndefined

from hsmmkit.config.schema import ProjectConfig

TOP = "(top level)"
TARGET = Path(__file__).resolve().parents[1] / "docs" / "guide" / "config.md"

INTRO = """# Configuration reference

<!-- Generated by scripts/gen_config_reference.py from the pydantic schema; do not edit by hand. -->

A project is described by one YAML file that validates against the pydantic v2 model tree below
(`extra="forbid"`: unknown keys are errors, ADR-0009). `hsmmkit validate-config` checks a file and writes
the fully resolved configuration (every default filled in); `hsmmkit config-schema OUT.json` exports the
JSON-Schema for editor support.

Types use the schema's own names; `required` marks fields without a default. Global CLI options
(`--seed`, `--device`, `--log-level`, `--out`, `--offline`) override `project.seed`, `estimation.device`,
`project.log_level`, `project.output_dir` and the cache policy for one invocation.
"""


def _models_in(annotation: Any) -> list[type[BaseModel]]:  # noqa: ANN401
    """Every pydantic model class mentioned in `annotation`, in order of appearance."""
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return [annotation]
    found: list[type[BaseModel]] = []
    for arg in typing.get_args(annotation):
        found += _models_in(arg)
    return found


def _type_name(annotation: Any) -> str:  # noqa: ANN401
    origin = typing.get_origin(annotation)
    args = typing.get_args(annotation)
    if annotation is None or annotation is type(None):
        return "None"
    if origin is typing.Literal:
        return " \\| ".join(repr(a) for a in args)
    if origin in (typing.Union, types.UnionType):
        return " \\| ".join(_type_name(a) for a in args)
    if origin is not None:
        inner = ", ".join(_type_name(a) for a in args)
        return f"{getattr(origin, '__name__', str(origin))}[{inner}]"
    if isinstance(annotation, type):
        return annotation.__name__
    return str(annotation).replace("typing.", "")


def _default(field: Any) -> str:  # noqa: ANN401
    if field.default is not PydanticUndefined:
        value = field.default
    elif field.default_factory is not None:
        value = field.default_factory()  # type: ignore[call-arg]
        if isinstance(value, BaseModel):
            return "section defaults"
    else:
        return "required"
    if value is None:
        return "`None`"
    if isinstance(value, PurePath):
        return f"`'{value.as_posix()}'`"  # the same text on every platform
    return f"`{value!s}`" if not isinstance(value, str) else f"`'{value}'`"


def _section(path: str, model: type[BaseModel]) -> tuple[list[str], list[tuple[str, type[BaseModel]]]]:
    lines = [f"## `{path}`", ""]
    doc = (model.__doc__ or "").strip().splitlines()
    if doc:
        lines += [doc[0].strip(), ""]
    lines += ["| Field | Type | Default |", "|---|---|---|"]
    children: list[tuple[str, type[BaseModel]]] = []
    for name, field in model.model_fields.items():
        lines.append(f"| `{name}` | `{_type_name(field.annotation)}` | {_default(field)} |")
        for child in _models_in(field.annotation):
            children.append((name if path == TOP else f"{path}.{name}", child))
    lines.append("")
    return lines, children


def render() -> str:
    """The full Markdown page."""
    out = [INTRO]
    seen: set[type[BaseModel]] = set()
    queue: list[tuple[str, type[BaseModel]]] = [(TOP, ProjectConfig)]
    while queue:
        path, model = queue.pop(0)
        if model in seen:
            continue
        seen.add(model)
        lines, children = _section(path, model)
        out.append("\n".join(lines))
        queue += children
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str]) -> int:
    """Write the page, or with `--check` compare it with the committed file."""
    text = render()
    if "--check" in argv:
        current = TARGET.read_text(encoding="utf-8").replace("\r\n", "\n") if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET} is stale; run `uv run python scripts/gen_config_reference.py`", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
